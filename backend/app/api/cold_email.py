"""Cold Email API endpoints — HTTP layer delegating to cold_email_service."""

import uuid

from fastapi import APIRouter, Depends, Query, Request, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models.user import User
from app.schemas.cold_email import (
    ColdEmailGenerateRequest,
    ColdEmailListItem,
    ColdEmailResponse,
)
from app.security.jwt import get_current_user
from app.security.rate_limiter import limiter
from app.services.cold_email_service import (
    delete_user_cold_email,
    generate_tailored_cold_email,
    get_user_cold_email,
    list_user_cold_emails,
)

router = APIRouter(prefix="/cold-emails", tags=["Cold Emails"])


@router.post(
    "/generate",
    response_model=ColdEmailResponse,
    summary="Generate a concise, hook-driven recruiter cold email from a job description",
)
@limiter.limit("5/minute")
async def generate_cold_email(
    request: Request,
    data: ColdEmailGenerateRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> ColdEmailResponse:
    """Generates a concise cold outreach email tailored to the role and recruiter."""
    record = await generate_tailored_cold_email(db, current_user, data)
    return ColdEmailResponse.model_validate(record)


@router.get(
    "/history",
    response_model=list[ColdEmailListItem],
    summary="List all generated cold emails for the user",
)
async def list_cold_emails(
    limit: int = Query(50, ge=1, le=100, description="Maximum number of items to return"),
    offset: int = Query(0, ge=0, description="Number of items to skip"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> list[ColdEmailListItem]:
    """Returns a paginated list of cold emails generated by the user."""
    items = await list_user_cold_emails(db, current_user.id, limit=limit, offset=offset)
    return [ColdEmailListItem.model_validate(item) for item in items]


@router.get(
    "/{cold_email_id}",
    response_model=ColdEmailResponse,
    summary="Get a specific generated cold email",
)
async def get_cold_email(
    cold_email_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> ColdEmailResponse:
    """Fetch details of a specific generated cold email."""
    record = await get_user_cold_email(db, cold_email_id, current_user.id)
    return ColdEmailResponse.model_validate(record)


@router.delete(
    "/{cold_email_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete a generated cold email",
)
async def delete_cold_email(
    cold_email_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> None:
    """Deletes a generated cold email record."""
    await delete_user_cold_email(db, cold_email_id, current_user.id)
