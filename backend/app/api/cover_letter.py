"""Cover Letter API endpoints — HTTP layer delegating to cover_letter_service."""

import uuid

from fastapi import APIRouter, Depends, Query, Request, status
from fastapi.responses import FileResponse
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models.user import User
from app.schemas.cover_letter import (
    CoverLetterGenerateRequest,
    CoverLetterListItem,
    CoverLetterResponse,
)
from app.security.jwt import get_current_user
from app.security.rate_limiter import limiter
from app.services.cover_letter_service import (
    delete_user_cover_letter,
    generate_tailored_cover_letter,
    get_cover_letter_download_info,
    get_user_cover_letter,
    list_user_cover_letters,
)

router = APIRouter(prefix="/cover-letters", tags=["Cover Letters"])


@router.post(
    "/generate",
    response_model=CoverLetterResponse,
    summary="Generate a concise single-page cover letter from a job description",
)
@limiter.limit("5/minute")
async def generate_cover_letter(
    request: Request,
    data: CoverLetterGenerateRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> CoverLetterResponse:
    """Generates a tailored plain-text cover letter (no ATS grading) capped to one A4 PDF page."""
    record = await generate_tailored_cover_letter(db, current_user, data)
    return CoverLetterResponse.model_validate(record)


@router.get(
    "/history",
    response_model=list[CoverLetterListItem],
    summary="List all generated cover letters for the user",
)
async def list_cover_letters(
    limit: int = Query(50, ge=1, le=100, description="Maximum number of items to return"),
    offset: int = Query(0, ge=0, description="Number of items to skip"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> list[CoverLetterListItem]:
    """Returns a paginated list of cover letters generated by the user."""
    items = await list_user_cover_letters(db, current_user.id, limit=limit, offset=offset)
    return [CoverLetterListItem.model_validate(item) for item in items]


@router.get(
    "/{cover_letter_id}",
    response_model=CoverLetterResponse,
    summary="Get a specific generated cover letter",
)
async def get_cover_letter(
    cover_letter_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> CoverLetterResponse:
    """Fetch details of a specific generated cover letter."""
    record = await get_user_cover_letter(db, cover_letter_id, current_user.id)
    return CoverLetterResponse.model_validate(record)


@router.get(
    "/{cover_letter_id}/download",
    summary="Download a generated cover letter as a one-page PDF",
)
async def download_cover_letter(
    cover_letter_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> FileResponse:
    """Returns the generated cover letter PDF file cleanly named for the candidate."""
    file_path, download_filename = await get_cover_letter_download_info(
        db, cover_letter_id, current_user
    )
    return FileResponse(
        path=file_path,
        filename=download_filename,
        media_type="application/pdf",
    )


@router.delete(
    "/{cover_letter_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete a generated cover letter and its stored PDF file",
)
async def delete_cover_letter(
    cover_letter_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> None:
    """Deletes a generated cover letter record and removes its stored PDF file."""
    await delete_user_cover_letter(db, cover_letter_id, current_user.id)
