"""API endpoints for generating, downloading, and managing tailored cover letters."""

import asyncio
import uuid
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Request, status
from fastapi.responses import FileResponse
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.agents.cover_letter_agent import process_cover_letter_generation
from app.database import get_db
from app.models.cover_letter import GeneratedCoverLetter
from app.models.user import User
from app.schemas.cover_letter import (
    CoverLetterGenerateRequest,
    CoverLetterListItem,
    CoverLetterResponse,
)
from app.security.jwt import get_current_user
from app.security.rate_limiter import limiter
from app.services.pdf_builder import generate_cover_letter_pdf
from app.utils.document_helpers import (
    build_pdf_download_response,
    delete_owned_document,
    get_owned_document_or_404,
    get_user_profile_or_400,
    resolve_candidate_identity,
)
from app.utils.file_handler import build_document_filename, get_generated_document_path

router = APIRouter(prefix="/cover-letters", tags=["Cover Letters"])


@router.post(
    "/generate",
    response_model=CoverLetterResponse,
    summary="Generate a concise single-page cover letter from a job description",
)
@limiter.limit("5/minute")
async def generate_cover_letter(
    request: Request,
    data: CoverLetterGenerateRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> CoverLetterResponse:
    """Generates a tailored plain-text cover letter (no ATS grading) capped to one A4 PDF page."""
    profile, profile_response = await get_user_profile_or_400(db, current_user.id)

    result = await process_cover_letter_generation(
        profile_response, data, user_name=current_user.name
    )
    if result.get("error") or not result.get("cover_letter"):
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=result.get("error") or "Failed to generate cover letter.",
        )

    cover_letter = result["cover_letter"]
    resolved_company = data.company_name or result.get("resolved_company")
    personal_info, user_name = resolve_candidate_identity(profile_response, current_user)

    cover_letter_id = uuid.uuid4()
    pdf_filename = build_document_filename(
        "cover-letter",
        resolved_company,
        user_name,
        unique_code=cover_letter_id.hex[:8],
    )
    pdf_path = get_generated_document_path(current_user.id, pdf_filename)

    try:
        await asyncio.to_thread(
            generate_cover_letter_pdf,
            cover_letter.cover_letter_text,
            personal_info,
            str(pdf_path),
            data.job_title,
            resolved_company,
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate cover letter PDF: {e}",
        )

    record = GeneratedCoverLetter(
        id=cover_letter_id,
        user_id=current_user.id,
        profile_id=profile.id,
        job_description=data.job_description,
        job_title=data.job_title,
        company_name=resolved_company,
        cover_letter_text=cover_letter.cover_letter_text,
        pdf_file_path=str(pdf_path),
        created_at=datetime.now(timezone.utc),
    )
    db.add(record)
    await db.commit()
    await db.refresh(record)

    return CoverLetterResponse.model_validate(record)


@router.get(
    "/history",
    response_model=list[CoverLetterListItem],
    summary="List all generated cover letters for the user",
)
async def list_cover_letters(
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> list[CoverLetterListItem]:
    """Returns a list of all cover letters generated by the user."""
    result = await db.execute(
        select(GeneratedCoverLetter)
        .where(GeneratedCoverLetter.user_id == current_user.id)
        .order_by(GeneratedCoverLetter.created_at.desc())
    )
    items = result.scalars().all()
    return [CoverLetterListItem.model_validate(item) for item in items]


@router.get(
    "/{cover_letter_id}",
    response_model=CoverLetterResponse,
    summary="Get a specific generated cover letter",
)
async def get_cover_letter(
    cover_letter_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> CoverLetterResponse:
    """Fetch details of a specific generated cover letter."""
    record = await get_owned_document_or_404(
        db,
        GeneratedCoverLetter,
        cover_letter_id,
        current_user.id,
        not_found_detail="Cover letter not found",
    )
    return CoverLetterResponse.model_validate(record)


@router.get(
    "/{cover_letter_id}/download",
    summary="Download a generated cover letter as a one-page PDF",
)
async def download_cover_letter(
    cover_letter_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> FileResponse:
    """Returns the generated cover letter PDF file cleanly named for the candidate."""
    return await build_pdf_download_response(
        db,
        GeneratedCoverLetter,
        cover_letter_id,
        current_user,
        filename_prefix="cover-letter",
        not_found_detail="Cover letter not found",
    )


@router.delete(
    "/{cover_letter_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete a generated cover letter and its stored PDF file",
)
async def delete_cover_letter(
    cover_letter_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> None:
    """Deletes a generated cover letter record and removes its stored PDF file."""
    await delete_owned_document(
        db,
        GeneratedCoverLetter,
        cover_letter_id,
        current_user.id,
        not_found_detail="Cover letter not found",
    )

