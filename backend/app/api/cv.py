"""CV API endpoints — HTTP layer delegating to cv_service."""

import uuid

from fastapi import APIRouter, Depends, Query, Request, status
from fastapi.responses import FileResponse
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models.user import User
from app.schemas.cv import CVGenerateRequest, CVListItem, CVResponse
from app.security.jwt import get_current_user
from app.security.rate_limiter import limiter
from app.services.cv_service import (
    delete_user_cv,
    generate_tailored_cv,
    get_cv_download_info,
    get_user_cv,
    list_user_cvs,
)

router = APIRouter(prefix="/cv", tags=["CV Generation"])


@router.post(
    "/generate",
    response_model=CVResponse,
    summary="Generate a tailored ATS CV from a job description",
)
@limiter.limit("5/minute")
async def generate_cv(
    request: Request,
    data: CVGenerateRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> CVResponse:
    """Generates a highly tailored CV based on the user's profile and the provided job description."""
    generated_cv = await generate_tailored_cv(db, current_user, data)
    return CVResponse.model_validate(generated_cv)


@router.get(
    "/history",
    response_model=list[CVListItem],
    summary="List all generated CVs for the user",
)
async def list_generated_cvs(
    limit: int = Query(50, ge=1, le=100, description="Maximum number of items to return"),
    offset: int = Query(0, ge=0, description="Number of items to skip"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> list[CVListItem]:
    """Returns a paginated list of tailored CVs generated by the user."""
    cvs = await list_user_cvs(db, current_user.id, limit=limit, offset=offset)
    return [CVListItem.model_validate(cv) for cv in cvs]


@router.get(
    "/{cv_id}",
    response_model=CVResponse,
    summary="Get a specific generated CV",
)
async def get_cv(
    cv_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> CVResponse:
    """Fetch details of a specifically generated CV."""
    cv = await get_user_cv(db, cv_id, current_user.id)
    return CVResponse.model_validate(cv)


@router.get(
    "/{cv_id}/download",
    summary="Download a generated CV as PDF",
)
async def download_cv(
    cv_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> FileResponse:
    """Returns the generated PDF file for the tailored CV without any internal unique code in the filename."""
    file_path, download_filename = await get_cv_download_info(db, cv_id, current_user)
    return FileResponse(
        path=file_path,
        filename=download_filename,
        media_type="application/pdf",
    )


@router.delete(
    "/{cv_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete a generated CV and its stored PDF file",
)
async def delete_cv(
    cv_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> None:
    """Deletes a generated CV record from the database and removes its PDF file from storage."""
    await delete_user_cv(db, cv_id, current_user.id)
